#!/usr/bin/env bash
# Bundle tests for the experiment harness.
#
#   bash tests/test_bundle.sh        # no database needed
#
# Builds the single-file bundle with tools/bundle.sh and asserts what makes it safe to
# deploy: it embeds every backend, resolves through the real registry, and produces
# byte-identical --list-backends / --dry-run output to the tree runner. The full
# benchmark-through-the-bundle smoke (needs a server) is run by tests/run_tests.sh via
# RUNNER=… tests/smoke_backend.sh.
set -euo pipefail

TESTS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SCRIPTS_DIR="$(cd "$TESTS_DIR/.." && pwd)"
cd "$SCRIPTS_DIR"

BUNDLE="$SCRIPTS_DIR/experiment.bundle.sh"
SUBSET="$SCRIPTS_DIR/experiment.bundle.subset.sh"
pass=0 fail=0
ok() { pass=$((pass + 1)); }
bad() { fail=$((fail + 1)); echo "FAIL: $*" >&2; }
cleanup() { rm -f "$BUNDLE" "$SUBSET"; }
trap cleanup EXIT

# --- generation -----------------------------------------------------------------------------
if ! bash tools/bundle.sh >/dev/null; then bad "tools/bundle.sh failed"; exit 1; fi
[[ -x "$BUNDLE" ]] && ok "bundle is executable" || bad "bundle missing or not executable"
grep -q 'GENERATED by tools/bundle.sh' "$BUNDLE" && ok "generated header present" \
    || bad "generated header missing"

# No shared-module source line may survive unrewritten: inside the bundle there are no
# per-backend files, so such a line would fail at load time on the target host.
if grep -qF '&& pwd)/_' "$BUNDLE"; then
    bad "unrewritten module source line in bundle"
else
    ok "shared-module sources rewritten"
fi

# Every backend of the tree must be bundled and every loader embedded.
mapfile -t tree_backends < <(./experiment.sh --list-backends | awk '{print $1}')
for b in "${tree_backends[@]}"; do
    grep -q "^_bundle_load_$b()" "$BUNDLE" || bad "loader for $b missing from bundle"
done
ok "all ${#tree_backends[@]} backend loaders embedded"

# --- behavioural equivalence with the tree runner --------------------------------------------
diff <(./experiment.sh --list-backends) <("$BUNDLE" --list-backends) >/dev/null \
    && ok "--list-backends identical to tree" \
    || bad "--list-backends differs from tree"

for b in "${tree_backends[@]}"; do
    if diff <(./experiment.sh "$b" --dry-run 2>&1) <("$BUNDLE" "$b" --dry-run 2>&1) >/dev/null; then
        ok "--dry-run identical to tree: $b"
    else
        bad "--dry-run differs from tree: $b"
    fi
done

# Aliases died with the legacy scripts (step 8c): a removed name must fail in the tree and
# in the bundle alike. (Their stderr may not be byte-identical - one lists available,
# the other bundled backends - so both rejections are asserted, not their text.)
if ./experiment.sh postgresql_array --dry-run >/dev/null 2>&1 ||
        "$BUNDLE" postgresql_array --dry-run >/dev/null 2>&1; then
    bad "removed alias still resolves (tree or bundle)"
else
    ok "removed alias rejected by tree and bundle"
fi
if "$BUNDLE" definitely_not_a_backend >/dev/null 2>&1; then
    bad "bundle accepted an unknown backend"
else
    ok "bundle rejects unknown backends"
fi

# --- selected-backend bundles -----------------------------------------------------------------
if ! bash tools/bundle.sh -o "$SUBSET" postgresql_row mongodb >/dev/null; then
    bad "tools/bundle.sh with a backend selection failed"
else
    mapfile -t subset < <("$SUBSET" --list-backends | awk '{print $1}')
    [[ "${subset[*]}" == "mongodb postgresql_row" ]] \
        && ok "subset bundle carries exactly the selected backends" \
        || bad "subset bundle has unexpected backends: ${subset[*]}"
    "$SUBSET" postgresql_row --dry-run >/dev/null 2>&1 \
        && ok "selected backend runs from subset" \
        || bad "selected backend failed in subset"
    if "$SUBSET" postgresql_textarray --dry-run >/dev/null 2>&1; then
        bad "subset bundle ran a backend it was not given"
    else
        ok "subset bundle refuses unbundled backends"
    fi
fi
rm -f "$SUBSET"

echo "[test_bundle] $pass passed, $fail failed"
(( fail == 0 ))
