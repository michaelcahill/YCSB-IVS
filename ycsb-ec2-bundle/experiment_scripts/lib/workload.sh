#!/usr/bin/env bash
# Part of the experiment runner; sourced, never executed directly.

# Workload files are INPUT, never scratch space.
#
# Every YCSB invocation gets its own immutable properties file under
# $WORKLOAD_DIR (default: $EXPERIMENT_DIR/workloads):
#
#   load-iter00.workload            reference-load-iter00.workload
#   extend-iter07.workload          run-iter07.workload
#   reference-iter07.workload       clean-run-iter07.workload
#   comparison-load-iter07.workload avg-run-iter07.workload
#
# Each file is the read-only template ($WORKLOAD_FILE) plus the phase overlay, and
# carries provenance (template path, sha256, phase, iteration) in its header. Nothing
# is ever rewritten, so a crashed run cannot poison the next one and a finished run can
# be replayed from its own artefacts. This replaces the 22 `perl -i -p` rewrites per run
# that the legacy scripts performed on files under version control.

# Template checksum, computed once per run by workload::init.
WORKLOAD_TEMPLATE_HASH=""

workload::hash() {
    local file="${1:?file required}"
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$file" | cut -d' ' -f1
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$file" | cut -d' ' -f1
    else
        printf 'unavailable\n'
    fi
}

# workload::get_value FILE KEY [DEFAULT] -> value of the last KEY= line, or DEFAULT.
workload::get_value() {
    local file="${1:?file required}" key="${2:?key required}" default="${3:-}" value
    value="$(grep -E "^[[:space:]]*${key}=" "$file" 2>/dev/null | tail -1 | cut -d'=' -f2-)"
    printf '%s\n' "${value:-$default}"
}

# Replace the first KEY= line (dropping later duplicates); append when absent.
workload::upsert_kv() {
    local file="${1:?file required}" key="${2:?key required}" value="${3-}" tmp
    tmp="$(mktemp "${file}.tmp.XXXXXX")"
    awk -v key="$key" -v val="$value" '
        $0 ~ "^"key"=" { if (!done) { print key "=" val; done = 1 }; next }
        { print }
        END { if (!done) print key "=" val }
    ' "$file" > "$tmp" && mv "$tmp" "$file"
}

# Add KEY=VALUE only when the file does not mention KEY at all. Mirrors the single
# conditional append the legacy scripts performed (fieldlengthdistribution).
workload::ensure_kv() {
    local file="${1:?file required}" key="${2:?key required}" value="${3-}"
    grep -qE "^[[:space:]]*${key}=" "$file" || printf '%s=%s\n' "$key" "$value" >> "$file"
}

# Check the template and prepare $WORKLOAD_DIR. Safe to call more than once.
workload::init() {
    [[ -r "$WORKLOAD_FILE" ]] || {
        echo "[error] workload template is not readable: $WORKLOAD_FILE" >&2
        return 1
    }
    mkdir -p "${WORKLOAD_DIR:?WORKLOAD_DIR is not set}" || return 1
    [[ -w "$WORKLOAD_DIR" ]] || {
        echo "[error] generated workload directory is not writable: $WORKLOAD_DIR" >&2
        return 1
    }
    if [[ -z "$WORKLOAD_TEMPLATE_HASH" ]]; then
        WORKLOAD_TEMPLATE_HASH="$(workload::hash "$WORKLOAD_FILE")"
        log "Workload template: $WORKLOAD_FILE sha256=$WORKLOAD_TEMPLATE_HASH"
    fi
}

# workload::generate PHASE ITERATION [KEY=VALUE ...] -> path of the new file.
#
# The overlay depends only on the phase, so every iteration is reproducible from the
# template plus the configuration. Extra KEY=VALUE arguments carry values the run feeds
# back into later phases (today: fieldlength for the comparison load).
workload::generate() {
    local phase="${1:?phase required (load|extend|run|reference|clean-run|avg-run|comparison-load)}"
    local iteration="${2:?iteration required}"
    shift 2
    local -a extra=("$@")

    local file
    file="$WORKLOAD_DIR/$(printf '%s-iter%02d.workload' "$phase" "$iteration")"

    {
        printf '# generated by experiment.sh\n'
        printf '# backend=%s phase=%s iteration=%s\n' \
            "${ACTIVE_BACKEND:-unknown}" "$phase" "$iteration"
        printf '# template=%s sha256=%s generated=%s\n' \
            "$WORKLOAD_FILE" "${WORKLOAD_TEMPLATE_HASH:-$(workload::hash "$WORKLOAD_FILE")}" \
            "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
        cat "$WORKLOAD_FILE"
    } > "$file"

    case "$phase" in
        load | reference-load)
            # The template already describes the initial load; fieldlength and its
            # distribution are supplied on the YCSB command line.
            ;;
        extend)
            workload::upsert_kv "$file" extendproportion "$extendproportion_extend"
            workload::upsert_kv "$file" readproportion "$readproportion_extend"
            workload::upsert_kv "$file" updateproportion "$updateproportion_extend"
            workload::upsert_kv "$file" scanproportion "$scanproportion_extend"
            workload::upsert_kv "$file" insertproportion "$insertproportion_extend"
            workload::upsert_kv "$file" readmodifywriteproportion "$readmodifywriteproportion_extend"
            workload::upsert_kv "$file" requestdistribution "$requestdistribution_extend"
            workload::upsert_kv "$file" readrequestdistribution "$readrequestdistribution_extend"
            workload::upsert_kv "$file" updaterequestdistribution "$updaterequestdistribution_extend"
            workload::upsert_kv "$file" operationcount "$extendoperationcount"
            ;;
        run | reference | clean-run | avg-run)
            workload::upsert_kv "$file" extendproportion "$extendproportion_postextend"
            workload::upsert_kv "$file" readproportion "$readproportion_postextend"
            workload::upsert_kv "$file" updateproportion "$updateproportion_postextend"
            workload::upsert_kv "$file" scanproportion "$scanproportion_postextend"
            workload::upsert_kv "$file" insertproportion "$insertproportion_postextend"
            workload::upsert_kv "$file" readmodifywriteproportion "$readmodifywriteproportion_postextend"
            workload::upsert_kv "$file" requestdistribution "$requestdistribution_postextend"
            workload::upsert_kv "$file" readrequestdistribution "$readrequestdistribution_postextend"
            workload::upsert_kv "$file" updaterequestdistribution "$updaterequestdistribution_postextend"
            workload::upsert_kv "$file" operationcount "${original_operationcount:?operationcount missing from the template}"
            # Measured runs read values sized like the extended database, so they need
            # a histogram; avg-run compares at the original value size instead.
            if [[ "$phase" == avg-run ]]; then
                workload::upsert_kv "$file" fieldlength "$fieldlengthoriginal"
            else
                workload::ensure_kv "$file" fieldlengthdistribution "${fieldlengthdistribution:-histogram}"
            fi
            ;;
        comparison-load)
            # Reload of the comparison database at the measured average value size.
            workload::upsert_kv "$file" fieldlength "${fieldlengthaverage:-$fieldlengthoriginal}"
            ;;
        *)
            echo "[error] no workload overlay is defined for phase: $phase" >&2
            return 2
            ;;
    esac

    # Scale presets may resize the dataset without editing the template.
    if [[ -n "${recordcount_override:-}" ]]; then
        workload::upsert_kv "$file" recordcount "$recordcount_override"
    fi

    local pair
    for pair in "${extra[@]}"; do
        workload::upsert_kv "$file" "${pair%%=*}" "${pair#*=}"
    done

    printf '%s\n' "$file"
}

# Publish the workload settings write_result records per row. The legacy scripts got
# these by sourcing the (mutated) workload file; reading them explicitly keeps the
# CSV columns identical without executing the properties file.
workload::apply_context() {
    local file="${1:?file required}" key
    for key in recordcount readallfields requestdistribution readrequestdistribution \
        updaterequestdistribution readproportion updateproportion scanproportion \
        insertproportion extendproportion; do
        printf -v "$key" '%s' "$(workload::get_value "$file" "$key")"
    done
}
