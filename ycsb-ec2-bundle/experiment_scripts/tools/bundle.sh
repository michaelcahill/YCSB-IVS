#!/usr/bin/env bash
#
# tools/bundle.sh — generate the single-file experiment harness.
#
#   tools/bundle.sh [-o FILE] [backend ...]        # default: every backend, ./experiment.bundle.sh
#
# The bundle inlines lib/*.sh and one function per selected backend module into a copy of
# experiment.sh, so the whole harness can be deployed with one scp onto an EC2 host that
# already carries the YCSB tree (the workflow the pre-refactor README used for its single
# script file). It is generated, never hand-edited: tests/test_bundle.sh rebuilds it and
# asserts tree/bundle equivalence, so the two cannot drift.
#
# Requirements of the generated file at its destination (unchanged from experiment.sh):
#   * it runs inside ycsb-ec2-bundle/experiment_scripts/ — YCSB lives in ../bin, and
#     conf/, workloads/ and watcher.sh are found relative to the script directory;
#   * conf/db.<backend>.env files stay on the server (they hold credentials and are not
#     bundled).
# The full directory stays the primary deploy path: tools/deploy.sh.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
LIB_DIR="$ROOT/lib"
BACKENDS_SRC_DIR="$LIB_DIR/backends"

OUT="$ROOT/experiment.bundle.sh"
requested=()

usage() {
    cat <<USAGE
Usage: tools/bundle.sh [-o FILE] [backend ...]

  -o, --output FILE   where to write the bundle (default: experiment.bundle.sh here)
  -h, --help          this help
  backend ...         backends to bundle (default: every backend in lib/backends)

Regenerates the single-file harness; see the header comment of the generated file.
USAGE
}

while (($#)); do
    case "$1" in
        -h | --help) usage; exit 0 ;;
        -o | --output) OUT="${2:?--output needs a file}"; shift 2 ;;
        -*) echo "[bundle] unknown option: $1" >&2; usage >&2; exit 2 ;;
        *) requested+=("$1"); shift ;;
    esac
done

# --- collect what goes in -------------------------------------------------------------------
all_backends=()
while IFS= read -r base; do all_backends+=("$base"); done < <(
    for f in "$BACKENDS_SRC_DIR"/*.sh; do
        base="$(basename "$f" .sh)"
        [[ "$base" == _* ]] && continue
        printf '%s\n' "$base"
    done | sort
)

backends=()
if (( ${#requested[@]} )); then
    for b in "${requested[@]}"; do
        [[ -f "$BACKENDS_SRC_DIR/$b.sh" ]] || {
            echo "[bundle] unknown backend: $b (available: ${all_backends[*]})" >&2
            exit 2
        }
        backends+=("$b")
    done
else
    backends=("${all_backends[@]}")
fi

# Shared modules (_*.sh) are not bundled as backends but must be embedded when a selected
# backend sources one. Discovery reads the exact source line that lib/backends/*.sh use.
MODULE_PFX='source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/'
modules=()
for b in "${backends[@]}"; do
    while read -r mod; do
        [[ -z "$mod" ]] && continue
        [[ " ${modules[*]:-} " == *" $mod "* ]] || modules+=("$mod")
    done < <(sed -n 's#.*&& pwd)/\(_[a-z0-9_]*\)\.sh".*#\1#p' "$BACKENDS_SRC_DIR/$b.sh")
done

# --- emit ------------------------------------------------------------------------------------
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

git_provenance() {
    local commit dirty=""
    commit="$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null)" || { echo "unknown"; return; }
    [[ -n "$(git -C "$ROOT" status --porcelain -- "$ROOT" 2>/dev/null)" ]] && dirty=" (dirty working tree)"
    printf '%s%s' "$commit" "$dirty"
}

{
    printf '#!/usr/bin/env bash\n'
    printf '# experiment.bundle.sh — GENERATED by tools/bundle.sh, DO NOT EDIT.\n'
    printf '# generated:  %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf '# source git: %s\n' "$(git_provenance)"
    printf '# backends:   %s\n' "${backends[*]}"
    printf '# modules:    %s\n' "${modules[*]:-<none>}"
    printf '#\n'
    printf '# Run it inside ycsb-ec2-bundle/experiment_scripts/ (it finds ../bin, conf/, workloads/\n'
    printf '# and watcher.sh relative to its own directory). Regenerate with: tools/bundle.sh\n'
} >"$tmp"

# The runner body: experiment.sh verbatim, with each `source "$LIB_DIR/x.sh"` line replaced
# by the content of that file. Order is preserved exactly, so inlining cannot change which
# definitions see which.
rewrite_lib_sources() {
    local line name last=-1 i=0
    local -a lines=()
    mapfile -t lines <"$ROOT/experiment.sh"
    for i in "${!lines[@]}"; do
        [[ "${lines[$i]}" =~ ^source\ \"\$LIB_DIR/([a-z_]+)\.sh\"$ ]] && last=$i
    done
    (( last >= 0 )) || { echo "[bundle] cannot find the lib source block in experiment.sh" >&2; return 1; }
    for i in "${!lines[@]}"; do
        line="${lines[$i]}"
        if [[ "$line" =~ ^source\ \"\$LIB_DIR/([a-z_]+)\.sh\"$ ]]; then
            name="${BASH_REMATCH[1]}"
            [[ -f "$LIB_DIR/$name.sh" ]] || { echo "[bundle] missing lib/$name.sh" >&2; return 1; }
            printf '# ---- inlined lib/%s.sh --------------------------------------------\n' "$name"
            cat "$LIB_DIR/$name.sh"
            if (( i == last )); then emit_bundle_runtime; fi
        else
            printf '%s\n' "$line"
        fi
    done
}

# Replace the shared-module source lines inside backend code with bundle loader calls, and
# fail if any other `source` line is present (a form this generator does not know would be
# silently dropped from the bundle).
embed_module_body() {
    local file="$1" line mod
    while IFS= read -r line || [[ -n "$line" ]]; do
        if [[ "$line" == source* ]]; then
            if [[ "$line" == "$MODULE_PFX"*\" ]]; then
                mod="${line#"$MODULE_PFX"}"
                mod="${mod%\"}"
                mod="${mod%.sh}"
                [[ -f "$BACKENDS_SRC_DIR/$mod.sh" ]] || {
                    echo "[bundle] $file sources unknown module: $mod" >&2; return 1
                }
                printf '    _bundle::module %s\n' "$mod"
                continue
            fi
            echo "[bundle] $file has a source line this generator does not understand:" >&2
            echo "         $line" >&2
            return 1
        fi
        printf '%s\n' "$line"
    done <"$file"
    return 0
}

emit_bundle_runtime() {
    cat <<'RUNTIME_HEADER'
# ============================================================================
# bundle runtime (generated by tools/bundle.sh): embedded modules/backends and
# the three registry hooks a file-less harness needs. Everything above this
# point is byte-identical to the tree runner, so behaviour cannot drift; these
# overrides only replace "find and source files" with "call embedded code".
# ============================================================================
RUNTIME_HEADER

    printf 'BUNDLE_BACKENDS=(%s)\n' "$(printf '\"%s\" ' "${backends[@]}")"
    cat <<'RUNTIME'

_bundle::module() {
    local name="${1:?module name required}" fn="_bundle_module_$1"
    declare -F "$fn" >/dev/null || {
        echo "[bundle] module $name was not bundled with the backends that need it" >&2
        return 2
    }
    "$fn"
}

# Registry overrides: discovery and loading consult BUNDLE_BACKENDS and the embedded
# loader functions instead of lib/backends/. resolve() still prints a path-like target
# (BACKENDS_DIR never exists inside a bundle) because ACTIVE_BACKEND is derived from it.
registry::available() {
    printf '%s\n' "${BUNDLE_BACKENDS[@]}" | sort
}

registry::resolve() {
    local name b
    name="${1:-}"
    for b in "${BUNDLE_BACKENDS[@]}"; do
        if [[ "$b" == "$name" ]]; then
            printf '%s\n' "$BACKENDS_DIR/$name.sh"
            return 0
        fi
    done
    {
        echo "[error] unknown backend: ${name:-<none>}"
        echo "bundled backends:"
        printf '  %s\n' "${BUNDLE_BACKENDS[@]}"
    } >&2
    return 2
}

registry::source_backend() {
    local name fn
    name="$(basename "${1:?resolved backend required}" .sh)"
    fn="_bundle_load_$name"
    declare -F "$fn" >/dev/null || {
        echo "[bundle] backend $name is not part of this bundle" >&2
        return 2
    }
    "$fn"
}

RUNTIME

    local m b
    for m in "${modules[@]}"; do
        printf '# ---- inlined lib/backends/%s.sh (shared module) ---------------------\n' "$m"
        printf '_bundle_module_%s() {\n' "$m"
        embed_module_body "$BACKENDS_SRC_DIR/$m.sh"
        printf '}\n\n'
    done
    for b in "${backends[@]}"; do
        printf '# ---- inlined lib/backends/%s.sh (backend %s) ------------------------\n' "$b" "$b"
        printf '_bundle_load_%s() {\n' "$b"
        embed_module_body "$BACKENDS_SRC_DIR/$b.sh"
        printf '}\n\n'
    done
}

rewrite_lib_sources >>"$tmp"

if ! bash -n "$tmp"; then
    echo "[bundle] generated bundle does not parse; refusing to write $OUT" >&2
    exit 1
fi

install -m 755 "$tmp" "$OUT"

# Self-check when the bundle sits in experiment_scripts/: --list-backends loads every
# bundled backend through the real registry path, so a broken inline or loader is caught
# here rather than by the next person who runs it. A bundle written elsewhere cannot run
# at all (it needs the YCSB tree around it), so there nothing can be checked.
if [[ "$(cd "$(dirname "$OUT")" && pwd)" == "$ROOT" ]]; then
    if ! "$OUT" --list-backends >/dev/null; then
        echo "[bundle] self-check FAILED: $OUT --list-backends" >&2
        exit 1
    fi
fi

echo "[bundle] wrote $OUT"
echo "[bundle] backends: ${backends[*]}"
echo "[bundle] shared modules: ${modules[*]:-<none>}"
